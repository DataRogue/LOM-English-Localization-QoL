		private static bool EnsureTableRevised()
		{
			if (_tableRevised != null)
			{
				return true;
			}
			if (_tableRevisedTried)
			{
				return false;
			}
			_tableRevisedTried = true;
			string basePath = OriginalMod.BaseTablePath;
			bool haveBase = File.Exists(basePath);
			bool haveOwn = File.Exists(RevisedTablePath);
			if (!haveBase && !haveOwn)
			{
				TableError = "missing " + Relative(RevisedTablePath) + ", and " + Plugin.BaseModName + " is not installed";
				Plugin.Log.LogWarning("string table 'revised': " + TableError);
				return false;
			}
			if (!haveOwn)
			{
				// Not an error that stops the layer: the original patch's table alone is served.
				TableError = "missing " + Relative(RevisedTablePath) + ": only the text of " + Plugin.BaseModName + " shows";
				Plugin.Log.LogWarning("string table 'revised': " + TableError);
			}
			try
			{
				TextTable.Table t = TextTable.LoadOverlay(haveBase ? basePath : null, haveOwn ? RevisedTablePath : null, "revised", OriginalMod.TableSentinelKeys);
				TextTable.LogStats(Plugin.Log, t);
				if (t.Count == 0)
				{
					TableError = "no rows read";
					Plugin.Log.LogWarning("string table 'revised': " + TableError);
					return false;
				}
				if (haveBase)
				{
					string detail;
					TableFileData = OriginalMod.VoteSample(true, t.BaseSample, out detail);
					TableFileVote = detail;
				}
				_tableRevised = t;
				return true;
			}
			catch (Exception ex)
			{
				TableError = ex.Message;
				Plugin.Log.LogError("string table 'revised' failed: " + ex);
				return false;
			}
		}

		private static bool EnsureTableOriginal()
		{
			if (_tableOriginal != null)
			{
				return true;
			}
			string basePath = OriginalMod.BaseTablePath;
			if (!File.Exists(basePath))
			{
				return false;
			}
			_tableOriginal = LoadTable(basePath, "original");
			if (_tableOriginal != null)
			{
				_tableOriginal.BasePath = basePath;
				Dictionary<string, string> sample = new Dictionary<string, string>(StringComparer.Ordinal);
				foreach (string k in OriginalMod.TableSentinelKeys)
				{
					string v;
					if (_tableOriginal.Map.TryGetValue(k, out v))
					{
						sample[k] = v;
					}
				}
				string detail;
				TableFileData = OriginalMod.VoteSample(true, sample, out detail);
				TableFileVote = detail;
			}
			return _tableOriginal != null;
		}

		private static TextTable.Table LoadTable(string path, string label)
		{
			if (!File.Exists(path))
			{
				TableError = "missing " + Relative(path);
				Plugin.Log.LogWarning("string table '" + label + "': " + TableError);
				return null;
			}
			try
			{
				TextTable.Table t = TextTable.Load(path, label);
				TextTable.LogStats(Plugin.Log, t);
				if (t.Count == 0)
				{
					TableError = "no rows read from " + Relative(path);
					Plugin.Log.LogWarning("string table '" + label + "': " + TableError);
					return null;
				}
				return t;
			}
			catch (Exception ex)
			{
				TableError = Relative(path) + ": " + ex.Message;
				Plugin.Log.LogError("string table '" + label + "' failed: " + ex);
				return null;
			}
		}

		private static bool EnsureSceneRevised()
		{
			if (_sceneRevised != null)
			{
				return true;
			}
			if (_sceneRevisedTried)
			{
				return false;
			}
			_sceneRevisedTried = true;
			try
			{
				_sceneRevised = LoadSceneRevisedCore();
				if (_sceneRevised != null)
				{
					NoteSceneFile(_sceneRevised);
				}
			}
			catch (Exception ex)
			{
				SceneError = ex.Message;
				Plugin.Log.LogError("scene text load failed: " + ex);
			}
			return _sceneRevised != null;
		}

		private static bool EnsureSceneOriginal()
		{
			if (_sceneOriginal != null)
			{
				return true;
			}
			if (!File.Exists(OriginalMod.BaseScenePath))
			{
				return false;
			}
			try
			{
				_sceneOriginal = LoadSceneOriginalCore();
				if (_sceneOriginal != null)
				{
					NoteSceneFile(_sceneOriginal);
				}
			}
			catch (Exception ex)
			{
				SceneError = ex.Message;
				Plugin.Log.LogError("scene text (original) load failed: " + ex);
			}
			return _sceneOriginal != null;
		}

		/// <summary>The data check on the base patch's scene file as read (main thread, after a load).</summary>
		private static void NoteSceneFile(SceneDictionary d)
		{
			if (d.BaseSample.Count == 0)
			{
				return;
			}
			string detail;
			SceneFileData = OriginalMod.VoteSample(false, d.BaseSample, out detail);
			SceneFileVote = detail;
		}

		/// <summary>
		/// The original patch's XUnity file with this mod's translation/scene/*.txt (ordinal order) laid over it; without that file,
		/// this mod's lines alone. Safe on a worker thread: no Unity calls; logging goes through the thread-safe BepInEx logger.
		/// </summary>
		private static SceneDictionary LoadSceneRevisedCore()
		{
			string[] files = Directory.Exists(RevisedSceneDir) ? Directory.GetFiles(RevisedSceneDir, "*.txt", SearchOption.TopDirectoryOnly) : new string[0];
			Array.Sort(files, StringComparer.Ordinal);
			string basePath = OriginalMod.BaseScenePath;
			bool haveBase = File.Exists(basePath);
			if (files.Length == 0 && !haveBase)
			{
				SceneError = "no *.txt files in " + Relative(RevisedSceneDir) + ", and " + Plugin.BaseModName + " is not installed";
				Plugin.Log.LogWarning("scene text 'revised': " + SceneError);
				return null;
			}
			if (files.Length == 0)
			{
				SceneError = "no *.txt files in " + Relative(RevisedSceneDir) + ": only the lines of " + Plugin.BaseModName + " show";
				Plugin.Log.LogWarning("scene text 'revised': " + SceneError);
			}
			Stopwatch sw = Stopwatch.StartNew();
			SceneDictionary d = SceneDictionary.LoadOverlay(haveBase ? basePath : null, files, OriginalMod.SceneSentinelKeys.ToList());
			d.Label = "revised";
			Plugin.Log.LogInfo($"scene text 'revised': " + (haveBase ? $"the original patch's file ({Relative(basePath)})" : "no original patch file (not installed)") + $" with this mod's {d.OverlayEntries} lines over it ({d.Substituted} replaced, {d.Removed} removed, {d.Added} added)");
			return Finish(d, "revised", sw);
		}

		/// <summary>The original patch's own XUnity file, as XUnity would read it.</summary>
		private static SceneDictionary LoadSceneOriginalCore()
		{
			Stopwatch sw = Stopwatch.StartNew();
			string basePath = OriginalMod.BaseScenePath;
			SceneDictionary d = SceneDictionary.LoadOverlay(basePath, new string[0], OriginalMod.SceneSentinelKeys.ToList());
			d.Label = "original";
			return Finish(d, "original", sw);
		}

		private static SceneDictionary Finish(SceneDictionary d, string label, Stopwatch sw)
		{
			Plugin.Log.LogInfo($"scene text '{label}': {d.Entries} lines from {d.Files.Count} file(s) in {sw.ElapsedMilliseconds} ms ({d.KeyCount} keys with whitespace variants, {d.RegexCount} regex, {d.Rejected} rejected, {d.Empty} empty, {d.Duplicates} duplicates)");
			foreach (string w in d.Warnings.Take(20))
			{
				Plugin.Log.LogInfo("  " + w);
			}
			if (d.Entries == 0)
			{
				SceneError = "no lines read (" + label + ")";
				return null;
			}
			return d;
		}

		private static string Relative(string path)
		{
			try
			{
				string root = Paths.GameRootPath.TrimEnd('\\', '/') + Path.DirectorySeparatorChar;
				return path.StartsWith(root, StringComparison.OrdinalIgnoreCase) ? path.Substring(root.Length).Replace('\\', '/') : path;
			}
			catch (Exception)
			{
				return path;
			}
		}
	}
