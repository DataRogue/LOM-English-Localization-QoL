"""Where the Legend of Mortal English text lives (LOM_UI_EN 0.5 and later: the revisions-only "overlay-1" layout).

Every tool that reads or writes translation data imports its paths from here, so the data can move without editing each
script. Three places, only one of which is shipped:

  WORKSPACE  LOM_Localization/workspace/            maintainer only, never shipped
             translation/StringTable.csv              the full working string table   (TABLE)
             translation/scene/scene_text.txt         the full working scene file     (SCENE)
             translation/scene/resize/*.resizer.txt   this mod's own resizers, if any (WS_RESIZE_DIR)
             strings/*.csv                            wording overrides with full notes (STRINGS_DIR)
             rules/*.json                             layout rules with their comments (WS_RULES_DIR)
             sentinels.json                           the data-check sentinel keys (hashes only)
             base_ref.lock                            md5s of the BASE_REF files this workspace is aligned with (WS_LOCK)
             nametips.tsv                             dialog name tips: character ids, extra name forms, portrait crops
                                                      (WS_NAMETIPS; tools/nametips/nametips.py; shipped byte for byte)
             factiontips.tsv                          faction tips: id, title, forms, this mod's spoiler-free description
                                                      (WS_FACTIONTIPS; the same tool; shipped byte for byte)
             translation/revision_record.tsv          per revised table row, the hashes of the game text and of the OverLlm
                                                      line it was revised against, kept from when it was revised (WS_RECORD;
                                                      written by publish.py only)
             translation/reviewed.tsv                 the review ledger: table keys a line-by-line review pass reviewed
                                                      (WS_LEDGER; key TAB pass TAB date, written through ledger.py)
             translation/scene/reviewed_scene.tsv     the same for scene lines, by their raw XUnity key as written in the
                                                      scene file, and 'resize/<file>' for this mod's own resizers
                                                      (WS_SCENE_LEDGER). A reviewed line ships even when its text is OverLlm's
  BASE_REF   LOM_Localization/base_ref/             maintainer only, never shipped: the OverLlm release the workspace
             StringTable.csv                          diverged from (BASE_REF_TABLE, BASE_REF_SCENE)
             _AutoGeneratedTranslations.txt
             resize/*.resizer.txt                     the release's resizers (to tell ours from theirs)
             game_source.tsv                          the game's own Chinese per key (a harness 'srcdump'; BASE_REF_SOURCE)
             history/NN-<stamp>/                      each earlier release the workspace was aligned with (kept by rebase;
                                                      BASE_REF_HISTORY), so its wording is still known as OverLlm's
  PLUGIN     BepInEx/plugins/LOM_UI_EN/              what players get: only this mod's own work
             translation/StringTable.csv              rows whose value differs from BASE_REF, or that the ledger lists (SHIP_TABLE)
             translation/StringTable.meta.tsv         per shipped row: hashes of the game text and of BASE_REF's line
             translation/scene/scene_text.txt         lines whose value differs or that the ledger lists, plus "key=" removals
                                                      (SHIP_SCENE)
             translation/scene/resize/*.resizer.txt   this mod's own resizers (copied from the workspace; a reviewed copy of
                                                      OverLlm's ships too when the scene ledger lists it)
             translation/MANIFEST.json                hashes only (SHIP_MANIFEST)
             strings/*.csv                            the overrides with notes stripped of quoted wording (SHIP_STRINGS_DIR)
             rules/*.json                             the rules without comments (SHIP_RULES_DIR)

Every editing tool reads and writes the WORKSPACE (TABLE / SCENE / STRINGS_DIR hold the full tables, so the tools work as
before) and calls publish() after a live write; publish.py derives the PLUGIN files from WORKSPACE minus BASE_REF. The
original OverLlm patch's installed files (BASE_TABLE, BASE_SCENE, BASE_RESIZE_DIR) belong to that patch and are only read.

Staging: stage(root) (or the environment variable LOM_STAGE=root, read at import) moves PLUGIN, WORKSPACE, BASE_REF, BACKUPS
and LOCALIZATION (the tools' change logs and their non-live output) under root/plugin, root/workspace, root/base_ref,
root/backups and root/localization, so a dry run never touches the real folders. TOOLS, PLUGIN_SRC and NOTICES_SRC stay the
real ones (read only). A staging root may not be, hold or sit inside the game folder or LOM_Localization.

Every guard here (inside, same_path, stage, assert_writable, assert_ledger_writable, guard_write, guard_under) resolves
paths first (os.path.realpath, plus os.path.samefile where both exist), so an 8.3 short name (C:/PROGRA~2/...), a junction or
a symbolic link cannot pass for another folder. The tools' output folders come from here and are checked the same way before
anything is written into them: log_dir(name) (a --live change log, LOCALIZATION/<name>), staged_dir(name) (non-live output),
backup_path / new_backup_dir (BACKUPS) and out_path(folder, name) for each file written into one of them; a junction or link
anywhere on the way (or a '..' in a name) that would carry the write out of its folder is refused.
"""
