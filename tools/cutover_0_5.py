"""One-time cut-over of LOM_UI_EN to the revisions-only layout (0.5, "overlay-1"): the plugin folder keeps only this mod's own
work, the full working tables and the rules with their comments move to LOM_Localization/workspace, the OverLlm release they
diverged from to LOM_Localization/base_ref (see lom_paths.py and publish.py).

  python cutover_0_5.py --stage DIR [--replace-stage] [--dll PATH]
        dry run: copies today's plugin folder to DIR/plugin (with PATH as its LOM_UI_EN.dll when given: the 0.5 build that
        will be installed, e.g. LOM_Localization/src/LOM_UI_EN/bin/LOM_UI_EN.dll) and does every step below with DIR/plugin,
        DIR/workspace, DIR/base_ref and DIR/backups. The real folders are only read.
  python cutover_0_5.py --live
        the real cut-over, on BepInEx/plugins/LOM_UI_EN, LOM_Localization/workspace, LOM_Localization/base_ref and
        LOM_Localization/backups. Install LOM_UI_EN 0.5.0 or later first: the cut-over refuses an older plugin DLL.
  python cutover_0_5.py --rollback BACKUP_DIR
        undoes a cut-over (the real layout; LOM_STAGE=DIR for a staged one): translation/, strings/, profiles/ and rules/
        come back from BACKUP_DIR (backups/pre-0.5-<stamp>) exactly, the files the cut-over added go, and the workspace and
        base_ref move to backups/rolled-back-<stamp>/. The cut-over can then run again.

Steps
  1. preflight, before anything is written: refuse if Mortal.exe is running (or that cannot be told), if the plugin DLL is
     older than 0.5.0, if the workspace or base_ref exist already, if the plugin folder was published into before
     (translation/.publish_state.json: roll that cut-over back first), or if the folder does not hold the 0.4 layout (full
     translation/StringTable.csv and scene/scene_text.txt, a 0.4 MANIFEST.json, profiles/original with the release's
     md5s, rules/). Then the whole cut-over runs in memory: the workspace with its data fixes, base_ref, the publish plan,
     its check, and the plugin-folder conflict and removal checks. Any refusal stops here, with nothing written.
  2. back up translation/ (MANIFEST.json, scene/resize and untranslated.txt included), strings/, profiles/ and rules/ to
     backups/pre-0.5-<stamp>/ with hashes.json (which also lists the files the cut-over adds), and check the copies
  3. WORKSPACE := translation/StringTable.csv, translation/scene/scene_text.txt, strings/*.csv and rules/*.json as the
     plugin has them, sentinels.json (the 24+24 MANIFEST sentinel keys with SHA-1 hashes, no text) and README.txt, with these
     data fixes applied (logged to backups/pre-0.5-<stamp>/datafix.tsv and LOM_Localization/cutover_0_5/; the backup holds
     the files before them):
       - scene lines that are XUnity's own runtime (Google) lines go: in the installed OverLlm XUnity file byte for byte, not
         in the release, not revised by this mod
       - wording overrides whose text is OverLlm's line for the key go when they change nothing (our table row has the same
         text) or are longer than 3 words; a short label that changes what the player sees stays; each decision is logged
       - wording overrides whose text holds a literal "[...]" / "[...unchanged...]" placeholder go, so the table text shows;
         their keys are listed for re-translation (retranslate.<stamp>.txt)
  4. BASE_REF := profiles/original/StringTable.csv and xunity_translations.txt (as _AutoGeneratedTranslations.txt), the 0.4
     copies of the release's resizers (resize/), README.txt, base_ref.json; then workspace/base_ref.lock
  5. publish.py build into the plugin folder (it replaces the 0.4 files, which the backup and the workspace hold, and removes
     translation/scene/resize and profiles/), then publish.py check
  6. summary: counts, sizes before and after, the backup, how to roll back
"""
